const { chromium } = require('/opt/node-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch(); const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  const out = [];
  await p.goto('http://localhost:3200/', { waitUntil: 'networkidle' });
  await p.keyboard.press('Tab');
  out.push(['KBD-1 first Tab = skip link', await p.evaluate(() => document.activeElement.textContent.trim()) === 'Skip to content']);
  await p.locator('[role=tab][aria-selected=true]').first().focus();
  await p.keyboard.press('ArrowRight');
  out.push(['KBD-2 ArrowRight moves tool tab', await p.evaluate(() => document.activeElement.textContent.trim()) === 'Edit image']);
  const ring = await p.evaluate(() => getComputedStyle(document.activeElement).outlineStyle);
  out.push(['KBD-3 visible focus outline on tab', ring !== 'none']);
  await p.setViewportSize({ width: 390, height: 844 });
  await p.goto('http://localhost:3200/', { waitUntil: 'networkidle' });
  const menuBtn = p.getByRole('button', { name: 'Open menu' });
  await menuBtn.focus(); await p.keyboard.press('Enter');
  out.push(['KBD-4 mobile menu opens as dialog', await p.locator('dialog[open]').count() === 1]);
  await p.keyboard.press('Escape');
  await p.waitForTimeout(200);
  out.push(['KBD-5 Escape closes menu, focus returns to trigger', await p.evaluate(() => document.activeElement.textContent.includes('Open menu'))]);
  await p.goto('http://localhost:3200/help', { waitUntil: 'networkidle' });
  await p.evaluate(() => localStorage.setItem('genlixs-preview-v3', JSON.stringify({ v: 2, signedIn: true, email: 'd@e.f' })));
  await p.setViewportSize({ width: 1280, height: 900 });
  await p.goto('http://localhost:3200/studio/credits', { waitUntil: 'networkidle' });
  const topup = p.getByRole('button', { name: 'Top up credits' });
  await topup.focus(); await p.keyboard.press('Enter');
  out.push(['KBD-6 dialog focus inside', await p.evaluate(() => !!document.activeElement.closest('dialog'))]);
  await p.keyboard.press('Escape'); await p.waitForTimeout(200);
  out.push(['KBD-7 focus restored to Top up', await p.evaluate(() => document.activeElement.textContent.trim()) === 'Top up credits']);
  await p.emulateMedia({ reducedMotion: 'reduce' });
  await p.goto('http://localhost:3200/', { waitUntil: 'networkidle' });
  const anim = await p.evaluate(() => getComputedStyle(document.querySelector('[data-reveal]')).animationName);
  out.push(['KBD-8 reduced motion disables section reveal', anim === 'none', anim]);
  await b.close();
  for (const o of out) console.log(o[1] ? 'PASS' : 'FAIL', o[0], o[2] ?? '');
})();
